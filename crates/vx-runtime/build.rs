//! Build-time stencil extraction (mirrors phon-jit's `build.rs`).
//!
//! On Apple Silicon, compile `stencils/stencils.rs` with rustc (`--emit=obj`) and
//! pull each stencil's machine code — and its continuation relocation offsets — out
//! of the object file, emitting a generated Rust file `src/lib.rs` `include!`s. The
//! compile + extraction machinery is the backend-agnostic `copypatch::extract`
//! (shared with phon's stencil JIT); this script supplies only the stencil symbol
//! names and the generated-constant codegen.
//!
//! Prefer nightly with `--cfg tailcall` so stencils chain via guaranteed tail calls
//! (`become`); fall back to a stable, call-based compile when nightly is absent
//! (both extract identically). On every other target, emit an empty table — the
//! portable interpreter (`src/kernel.rs`) is the path there.

use std::{env, fs, path::Path, path::PathBuf};

use copypatch::extract::{compile_object, extract_stencil_n, nightly_available};

/// A stencil's continuation symbols, each paired with the suffix for the
/// reloc-offset const it emits (`vx_cont` → `CONT`, `vx_cont_then` → `THEN`, …).
type Conts = &'static [(&'static str, &'static str)];

/// One stencil: `(symbol, CONST_NAME, continuations)`. The ops have one
/// continuation (`vx_cont` → `NAME_CONT`); `branch` has two (`then`/`else` →
/// `NAME_THEN`/`NAME_ELSE`); the terminators (`smoke`, `fail`, `return`) none.
type StencilEntry = (&'static str, &'static str, Conts);

const STENCILS: &[StencilEntry] = &[
    ("vx_stencil_smoke", "SMOKE", &[]),
    ("vx_stencil_const", "CONST", &[("vx_cont", "CONT")]),
    ("vx_stencil_copy", "COPY", &[("vx_cont", "CONT")]),
    ("vx_stencil_add", "ADD", &[("vx_cont", "CONT")]),
    ("vx_stencil_sub", "SUB", &[("vx_cont", "CONT")]),
    ("vx_stencil_mul", "MUL", &[("vx_cont", "CONT")]),
    ("vx_stencil_div", "DIV", &[("vx_cont", "CONT")]),
    ("vx_stencil_rem", "REM", &[("vx_cont", "CONT")]),
    ("vx_stencil_eq", "EQ", &[("vx_cont", "CONT")]),
    ("vx_stencil_ne", "NE", &[("vx_cont", "CONT")]),
    ("vx_stencil_lt", "LT", &[("vx_cont", "CONT")]),
    ("vx_stencil_le", "LE", &[("vx_cont", "CONT")]),
    ("vx_stencil_gt", "GT", &[("vx_cont", "CONT")]),
    ("vx_stencil_ge", "GE", &[("vx_cont", "CONT")]),
    ("vx_stencil_and", "AND", &[("vx_cont", "CONT")]),
    ("vx_stencil_or", "OR", &[("vx_cont", "CONT")]),
    ("vx_stencil_not", "NOT", &[("vx_cont", "CONT")]),
    ("vx_stencil_jump", "JUMP", &[("vx_cont", "CONT")]),
    (
        "vx_stencil_branch",
        "BRANCH",
        &[("vx_cont_then", "THEN"), ("vx_cont_else", "ELSE")],
    ),
    ("vx_stencil_fail", "FAIL", &[]),
    ("vx_stencil_return", "RETURN", &[]),
];

fn main() {
    println!("cargo:rustc-check-cfg=cfg(vx_jit_tailcall)");

    let out = PathBuf::from(env::var("OUT_DIR").unwrap());
    let generated = out.join("stencils.rs");

    let target_os = env::var("CARGO_CFG_TARGET_OS").unwrap_or_default();
    let target_arch = env::var("CARGO_CFG_TARGET_ARCH").unwrap_or_default();

    if target_os == "macos" && target_arch == "aarch64" {
        emit_arm64_macos(&out, &generated);
    } else {
        // Empty table — the interpreter is the path on this target.
        let mut s = String::new();
        for (_, name, conts) in STENCILS {
            s.push_str(&format!("pub const {name}: &[u8] = &[];\n"));
            for (_, suffix) in *conts {
                s.push_str(&format!("pub const {name}_{suffix}: &[usize] = &[];\n"));
            }
        }
        fs::write(&generated, s).unwrap();
    }
}

fn emit_arm64_macos(out: &Path, generated: &Path) {
    println!("cargo:rerun-if-changed=stencils/stencils.rs");
    println!("cargo:rerun-if-changed=build.rs");

    let target = env::var("TARGET").expect("TARGET set by cargo");
    let obj = out.join("stencils.o");
    let src = Path::new("stencils/stencils.rs");

    // Prefer nightly tail-call stencils; fall back to stable call-based ones.
    let tailcall =
        nightly_available() && compile_object("rustc", &["+nightly"], src, &obj, &target, true);
    if tailcall {
        println!("cargo:rustc-cfg=vx_jit_tailcall");
    } else {
        let rustc = env::var("RUSTC").unwrap_or_else(|_| "rustc".to_string());
        assert!(
            compile_object(&rustc, &[], src, &obj, &target, false),
            "rustc failed to compile stencils"
        );
    }

    let bytes = fs::read(&obj).unwrap();
    let symbols: Vec<&str> = STENCILS.iter().map(|(sym, _, _)| *sym).collect();

    let mode = if tailcall {
        "tail-call (nightly become)"
    } else {
        "call (stable)"
    };
    let mut s =
        format!("// Generated by build.rs from stencils/stencils.rs (rustc --emit=obj, {mode}).\n");
    for (sym, name, conts) in STENCILS {
        let cont_syms: Vec<&str> = conts.iter().map(|(cs, _)| *cs).collect();
        let st = extract_stencil_n(&bytes, &symbols, sym, &cont_syms);
        s.push_str(&format!(
            "/// `{sym}` machine code.\npub const {name}: &[u8] = &{:?};\n",
            st.bytes
        ));
        for ((cont_sym, suffix), relocs) in conts.iter().zip(&st.cont_relocs) {
            s.push_str(&format!(
                "/// Offsets within `{name}` of the `{cont_sym}` BRANCH26 relocations.\n\
                 pub const {name}_{suffix}: &[usize] = &{relocs:?};\n"
            ));
        }
    }
    fs::write(generated, s).unwrap();
}
