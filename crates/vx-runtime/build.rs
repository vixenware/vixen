//! Build-time stencil extraction (mirrors phon-jit's `build.rs`).
//!
//! On Apple Silicon, compile `stencils/stencils.rs` with rustc (`--emit=obj`) and
//! pull each stencil's machine code — and its `vx_cont` relocation offsets — out of
//! the object file, emitting a generated Rust file `src/lib.rs` `include!`s. The
//! compile + extraction machinery is the backend-agnostic `copypatch::extract`
//! (shared with phon's stencil JIT); this script supplies only the stencil symbol
//! names and the generated-constant codegen.
//!
//! Prefer nightly with `--cfg tailcall` so stencils chain via guaranteed tail calls
//! (`become`); fall back to a stable, call-based compile when nightly is absent
//! (both extract identically). On every other target, emit an empty table — the
//! portable interpreter (`src/kernel.rs`) is the path there.

use std::{env, fs, path::Path, path::PathBuf};

use copypatch::extract::{Stencil, compile_object, extract_stencil, nightly_available};

/// `(symbol, CONST_NAME, chains)`. `chains` ops continue via a `vx_cont` BRANCH26
/// (so their `_CONT` offsets are emitted); the terminators (`smoke`, `fail`,
/// `return`) just `ret`.
const STENCILS: &[(&str, &str, bool)] = &[
    ("vx_stencil_smoke", "SMOKE", false),
    ("vx_stencil_const", "CONST", true),
    ("vx_stencil_copy", "COPY", true),
    ("vx_stencil_add", "ADD", true),
    ("vx_stencil_sub", "SUB", true),
    ("vx_stencil_mul", "MUL", true),
    ("vx_stencil_div", "DIV", true),
    ("vx_stencil_rem", "REM", true),
    ("vx_stencil_eq", "EQ", true),
    ("vx_stencil_ne", "NE", true),
    ("vx_stencil_lt", "LT", true),
    ("vx_stencil_le", "LE", true),
    ("vx_stencil_gt", "GT", true),
    ("vx_stencil_ge", "GE", true),
    ("vx_stencil_and", "AND", true),
    ("vx_stencil_or", "OR", true),
    ("vx_stencil_not", "NOT", true),
    ("vx_stencil_fail", "FAIL", false),
    ("vx_stencil_return", "RETURN", false),
];

fn main() {
    println!("cargo:rustc-check-cfg=cfg(vx_jit_tailcall)");

    let out = PathBuf::from(env::var("OUT_DIR").unwrap());
    let generated = out.join("stencils.rs");

    let target_os = env::var("CARGO_CFG_TARGET_OS").unwrap_or_default();
    let target_arch = env::var("CARGO_CFG_TARGET_ARCH").unwrap_or_default();

    if target_os == "macos" && target_arch == "aarch64" {
        emit_arm64_macos(&out, &generated);
    } else {
        // Empty table — the interpreter is the path on this target.
        let mut s = String::new();
        for (_, name, chains) in STENCILS {
            s.push_str(&format!("pub const {name}: &[u8] = &[];\n"));
            if *chains {
                s.push_str(&format!("pub const {name}_CONT: &[usize] = &[];\n"));
            }
        }
        fs::write(&generated, s).unwrap();
    }
}

fn emit_arm64_macos(out: &Path, generated: &Path) {
    println!("cargo:rerun-if-changed=stencils/stencils.rs");
    println!("cargo:rerun-if-changed=build.rs");

    let target = env::var("TARGET").expect("TARGET set by cargo");
    let obj = out.join("stencils.o");
    let src = Path::new("stencils/stencils.rs");

    // Prefer nightly tail-call stencils; fall back to stable call-based ones.
    let tailcall =
        nightly_available() && compile_object("rustc", &["+nightly"], src, &obj, &target, true);
    if tailcall {
        println!("cargo:rustc-cfg=vx_jit_tailcall");
    } else {
        let rustc = env::var("RUSTC").unwrap_or_else(|_| "rustc".to_string());
        assert!(
            compile_object(&rustc, &[], src, &obj, &target, false),
            "rustc failed to compile stencils"
        );
    }

    let bytes = fs::read(&obj).unwrap();
    let symbols: Vec<&str> = STENCILS.iter().map(|(sym, _, _)| *sym).collect();

    let mode = if tailcall {
        "tail-call (nightly become)"
    } else {
        "call (stable)"
    };
    let mut s =
        format!("// Generated by build.rs from stencils/stencils.rs (rustc --emit=obj, {mode}).\n");
    for (sym, name, chains) in STENCILS {
        let st: Stencil = extract_stencil(&bytes, &symbols, sym, "vx_cont");
        s.push_str(&format!(
            "/// `{sym}` machine code.\npub const {name}: &[u8] = &{:?};\n",
            st.bytes
        ));
        if *chains {
            s.push_str(&format!(
                "/// Byte offsets within `{name}` of the `vx_cont` BRANCH26 relocations.\n\
                 pub const {name}_CONT: &[usize] = &{:?};\n",
                st.cont_relocs
            ));
        }
    }
    fs::write(generated, s).unwrap();
}
