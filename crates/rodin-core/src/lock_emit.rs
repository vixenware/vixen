use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;

use rodin_facts::{FeatIx, PkgIx};
use semver::Version;

use crate::{CompiledIndex, parse_req, scoped_feature_name};

#[derive(Clone, Debug, Eq, PartialEq)]
pub struct LockDependency {
    pub name: String,
    pub version: Version,
    pub source: Option<String>,
    pub lock_entry: Option<String>,
}

#[derive(Clone, Debug, Eq, PartialEq)]
pub struct LockPackageRow {
    pub name: String,
    pub version: Version,
    pub source: Option<String>,
    pub checksum: Option<String>,
    pub dependencies: Vec<LockDependency>,
}

#[must_use]
pub fn emit_lock(result: &crate::SolveResult) -> String {
    render_lock_packages(&result.lock_packages)
}

pub(crate) fn render_lock_packages(packages: &[LockPackageRow]) -> String {
    let mut packages = packages.to_vec();
    packages.sort_by(|left, right| {
        left.name
            .cmp(&right.name)
            .then_with(|| left.version.cmp(&right.version))
            .then_with(|| left.source.cmp(&right.source))
    });

    let selected = SelectedPackageIndex::new(&packages);
    let mut out = String::new();
    out.push_str("# This file is automatically @generated by Cargo.\n");
    out.push_str("# It is not intended for manual editing.\n");
    out.push_str("version = 4\n\n");
    for (ix, package) in packages.iter().enumerate() {
        if ix > 0 {
            out.push('\n');
        }
        out.push_str("[[package]]\n");
        let _ = writeln!(out, "name = {}", toml_quote(&package.name));
        let _ = writeln!(
            out,
            "version = {}",
            toml_quote(&package.version.to_string())
        );
        if let Some(source) = &package.source {
            let _ = writeln!(out, "source = {}", toml_quote(source));
        }
        if let Some(checksum) = &package.checksum {
            let _ = writeln!(out, "checksum = {}", toml_quote(checksum));
        }
        if !package.dependencies.is_empty() {
            out.push_str("dependencies = [\n");
            let mut deps = package
                .dependencies
                .iter()
                .map(|dep| {
                    dep.lock_entry
                        .clone()
                        .unwrap_or_else(|| selected.render_dependency(dep))
                })
                .collect::<Vec<_>>();
            deps.sort();
            deps.dedup();
            for dep in deps {
                let _ = writeln!(out, " {},", toml_quote(&dep));
            }
            out.push_str("]\n");
        }
    }
    out
}

pub(crate) fn build_lock_packages(
    index: &CompiledIndex,
    selected: &BTreeMap<String, Version>,
    enabled_features: &BTreeSet<(PkgIx, FeatIx)>,
) -> Vec<LockPackageRow> {
    let selected_by_pkg = selected
        .iter()
        .filter_map(|(label, version)| index.package(label).map(|pkg| (pkg, version.clone())))
        .collect::<BTreeMap<_, _>>();
    let mut packages = Vec::new();
    for (pkg, version) in &selected_by_pkg {
        let Some(manifest) = index.manifests.get(&(*pkg, version.clone())) else {
            continue;
        };
        let name = index.base_name(*pkg).unwrap_or_default().to_owned();
        let mut dependencies = manifest
            .lock
            .dependency_entries
            .as_ref()
            .map(|entries| {
                entries
                    .iter()
                    .map(|entry| LockDependency {
                        name: lock_entry_name(entry),
                        version: Version::new(0, 0, 0),
                        source: None,
                        lock_entry: Some(entry.clone()),
                    })
                    .collect::<Vec<_>>()
            })
            .unwrap_or_else(|| {
                manifest_dependencies(index, &selected_by_pkg, enabled_features, *pkg, manifest)
            });
        dependencies.sort_by(|left, right| {
            left.name
                .cmp(&right.name)
                .then_with(|| left.version.cmp(&right.version))
                .then_with(|| left.source.cmp(&right.source))
                .then_with(|| left.lock_entry.cmp(&right.lock_entry))
        });
        dependencies.dedup();
        packages.push(LockPackageRow {
            name,
            version: version.clone(),
            source: manifest.lock.source.clone(),
            checksum: manifest.lock.checksum.clone(),
            dependencies,
        });
    }
    packages
}

fn manifest_dependencies(
    index: &CompiledIndex,
    selected_by_pkg: &BTreeMap<PkgIx, Version>,
    enabled_features: &BTreeSet<(PkgIx, FeatIx)>,
    pkg: PkgIx,
    manifest: &crate::Manifest,
) -> Vec<LockDependency> {
    let mut dependencies = Vec::new();
    for dep in &manifest.deps {
        if dep.optional && !optional_dependency_enabled(index, enabled_features, pkg, dep) {
            continue;
        }
        let Ok(req) = parse_req(&dep.req) else {
            continue;
        };
        let Some(dep_pkg) = index.package_for_set(&dep.actual, &req, dep.class_hint) else {
            continue;
        };
        let Some(dep_version) = selected_by_pkg.get(&dep_pkg) else {
            continue;
        };
        let dep_manifest = index.manifests.get(&(dep_pkg, dep_version.clone()));
        dependencies.push(LockDependency {
            name: index.base_name(dep_pkg).unwrap_or(&dep.actual).to_owned(),
            version: dep_version.clone(),
            source: dep_manifest.and_then(|manifest| manifest.lock.source.clone()),
            lock_entry: None,
        });
    }
    dependencies
}

fn lock_entry_name(entry: &str) -> String {
    entry
        .split_whitespace()
        .next()
        .unwrap_or_default()
        .to_owned()
}

fn optional_dependency_enabled(
    index: &CompiledIndex,
    enabled_features: &BTreeSet<(PkgIx, FeatIx)>,
    pkg: PkgIx,
    dep: &crate::DepLine,
) -> bool {
    let names = [
        scoped_feature_name(&dep.kind, &dep.key),
        scoped_feature_name(&dep.kind, &format!("dep:{}", dep.key)),
    ];
    names.iter().any(|name| {
        index
            .features
            .get(name)
            .is_some_and(|feat| enabled_features.contains(&(pkg, feat)))
    })
}

struct SelectedPackageIndex<'a> {
    by_name: BTreeMap<&'a str, usize>,
    by_name_version: BTreeMap<(&'a str, &'a Version), usize>,
}

impl<'a> SelectedPackageIndex<'a> {
    fn new(packages: &'a [LockPackageRow]) -> Self {
        let mut by_name = BTreeMap::new();
        let mut by_name_version = BTreeMap::new();
        for package in packages {
            *by_name.entry(package.name.as_str()).or_default() += 1;
            *by_name_version
                .entry((package.name.as_str(), &package.version))
                .or_default() += 1;
        }
        Self {
            by_name,
            by_name_version,
        }
    }

    fn render_dependency(&self, dep: &LockDependency) -> String {
        if self
            .by_name
            .get(dep.name.as_str())
            .copied()
            .unwrap_or_default()
            <= 1
        {
            return dep.name.clone();
        }
        if self
            .by_name_version
            .get(&(dep.name.as_str(), &dep.version))
            .copied()
            .unwrap_or_default()
            <= 1
        {
            return format!("{} {}", dep.name, dep.version);
        }
        match &dep.source {
            Some(source) => format!("{} {} ({source})", dep.name, dep.version),
            None => format!("{} {}", dep.name, dep.version),
        }
    }
}

fn toml_quote(value: &str) -> String {
    let mut out = String::with_capacity(value.len() + 2);
    out.push('"');
    for ch in value.chars() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            ch if ch.is_control() => {
                let _ = write!(out, "\\u{:04x}", ch as u32);
            }
            ch => out.push(ch),
        }
    }
    out.push('"');
    out
}

#[cfg(test)]
mod tests {
    use std::collections::BTreeMap;

    use eyre::Result;
    use pretty_assertions::assert_eq;

    use crate::{CompiledIndex, Problem, RootReq, SyntheticDep, emit_lock, solve};

    #[test]
    fn emits_crate_vix_lock_graph_schema_fixture() -> Result<()> {
        let mut index = CompiledIndex::empty();
        let version = semver::Version::parse("0.1.0")?;
        index.add_package_version(
            "mini_app",
            version.clone(),
            vec![
                SyntheticDep::normal("alpha_lib", "=0.1.0"),
                SyntheticDep::normal("formatting_lib", "=0.1.0"),
            ],
            BTreeMap::new(),
        );
        index.add_package_version(
            "alpha_lib",
            version.clone(),
            vec![SyntheticDep::normal("core_lib", "=0.1.0")],
            BTreeMap::new(),
        );
        index.add_package_version("core_lib", version.clone(), Vec::new(), BTreeMap::new());
        index.add_package_version("formatting_lib", version, Vec::new(), BTreeMap::new());
        index.finish_synthetic()?;

        let result = solve(
            &index,
            Problem::new(vec![RootReq::new("mini_app", "=0.1.0")]),
        )
        .map_err(|err| eyre::eyre!("{err:?}"))?;
        assert_eq!(
            emit_lock(&result),
            r#"# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "alpha_lib"
version = "0.1.0"
dependencies = [
 "core_lib",
]

[[package]]
name = "core_lib"
version = "0.1.0"

[[package]]
name = "formatting_lib"
version = "0.1.0"

[[package]]
name = "mini_app"
version = "0.1.0"
dependencies = [
 "alpha_lib",
 "formatting_lib",
]
"#
        );
        Ok(())
    }
}
